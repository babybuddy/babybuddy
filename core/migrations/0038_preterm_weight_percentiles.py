def add_preterm_weights(apps, schema_editor):
    WeightPercentile = apps.get_model("core", "WeightPercentile")
    rows = []
    for sex, table in _DATA:
        for day, p3, p15, p50, p85, p97 in table:
            rows.append(
                WeightPercentile(
                    age_in_days=timedelta(days=day),
                    p3_weight=p3,
                    p15_weight=p15,
                    p50_weight=p50,
                    p85_weight=p85,
                    p97_weight=p97,
                    sex=sex,
                )
            )
    WeightPercentile.objects.bulk_create(rows, ignore_conflicts=True)


def remove_preterm_weights(apps, schema_editor):
    WeightPercentile = apps.get_model("core", "WeightPercentile")
    for sex, table in _DATA:
        WeightPercentile.objects.filter(
            sex=sex,
            age_in_days__in=[timedelta(days=day) for (day, *_rest) in table],
        ).delete()


